# Creates .env from .env.example, replacing every placeholder with a random secret.
# Usage (from the project folder):
#   powershell -ExecutionPolicy Bypass -File scripts\generate-env.ps1
# Secrets are generated on this machine and never printed.

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$example = Join-Path $root '.env.example'
$target = Join-Path $root '.env'

if (Test-Path $target) {
    Write-Host '.env already exists; nothing was changed. Delete it first to regenerate.'
    exit 1
}

$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
function New-RandomBytes([int]$count) {
    $bytes = New-Object byte[] $count
    $rng.GetBytes($bytes)
    return , $bytes
}
function New-HexSecret([int]$count) {
    return ((New-RandomBytes $count) | ForEach-Object { $_.ToString('x2') }) -join ''
}
# Fernet key = URL-safe base64 of 32 random bytes
$fernet = [Convert]::ToBase64String((New-RandomBytes 32)).Replace('+', '-').Replace('/', '_')

$content = [IO.File]::ReadAllText($example)
$content = $content.Replace('# Copy this file to .env and change the values. Never commit .env.',
                            '# Generated by scripts/generate-env.ps1. Never commit this file.')
$content = [regex]::Replace($content, '(?m)^AIRFLOW_FERNET_KEY=\r?$', "AIRFLOW_FERNET_KEY=$fernet")
$content = $content.Replace('change-me-to-a-long-random-string', (New-HexSecret 32))
$content = [regex]::Replace($content, '(?m)^(\w+)=change-me\r?$', {
    param($match)
    return "$($match.Groups[1].Value)=$(New-HexSecret 16)"
})

if ($content -match 'change-me') { throw 'A placeholder was not replaced; .env not written.' }

# UTF-8 without BOM, so Docker Compose reads it correctly
[IO.File]::WriteAllText($target, $content, (New-Object System.Text.UTF8Encoding $false))
Write-Host '.env created. Admin user and password are in AIRFLOW_ADMIN_USER / AIRFLOW_ADMIN_PASSWORD.'
