-- GOLD: star schema for analytics. Grain of the fact = one invoice line.

CREATE TABLE IF NOT EXISTS gold.dim_date (
    date_key     INTEGER     PRIMARY KEY,            -- YYYYMMDD
    full_date    DATE        NOT NULL UNIQUE,
    year         SMALLINT    NOT NULL,
    quarter      SMALLINT    NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month        SMALLINT    NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name   VARCHAR(10) NOT NULL,
    day          SMALLINT    NOT NULL CHECK (day BETWEEN 1 AND 31),
    day_of_week  SMALLINT    NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- ISO: 1 = Monday
    is_weekend   BOOLEAN     NOT NULL
);

CREATE TABLE IF NOT EXISTS gold.dim_product (
    product_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_code   VARCHAR(20) NOT NULL UNIQUE,
    description  TEXT
);

CREATE TABLE IF NOT EXISTS gold.dim_customer (
    customer_key         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id          INTEGER UNIQUE,              -- NULL only for the unknown member
    first_purchase_date  DATE,
    last_purchase_date   DATE
);

CREATE TABLE IF NOT EXISTS gold.dim_country (
    country_key   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_name  VARCHAR(60) NOT NULL UNIQUE
);

-- Unknown members: sales without a customer still count in every total.
INSERT INTO gold.dim_customer (customer_key, customer_id)
VALUES (-1, NULL)
ON CONFLICT (customer_key) DO NOTHING;

INSERT INTO gold.dim_country (country_key, country_name)
VALUES (-1, 'Unknown')
ON CONFLICT (country_key) DO NOTHING;

CREATE TABLE IF NOT EXISTS gold.fact_sales (
    sales_key        BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    line_key         CHAR(32)       NOT NULL UNIQUE,   -- natural key from Silver
    invoice_no       VARCHAR(20)    NOT NULL,          -- degenerate dimension
    date_key         INTEGER        NOT NULL REFERENCES gold.dim_date (date_key),
    product_key      INTEGER        NOT NULL REFERENCES gold.dim_product (product_key),
    customer_key     INTEGER        NOT NULL REFERENCES gold.dim_customer (customer_key),
    country_key      INTEGER        NOT NULL REFERENCES gold.dim_country (country_key),
    quantity         INTEGER        NOT NULL,
    unit_price       NUMERIC(10, 2) NOT NULL,
    line_total       NUMERIC(12, 2) NOT NULL,
    is_cancellation  BOOLEAN        NOT NULL
);

-- Foreign keys are not indexed automatically in PostgreSQL
CREATE INDEX IF NOT EXISTS ix_fact_sales_date_key     ON gold.fact_sales (date_key);
CREATE INDEX IF NOT EXISTS ix_fact_sales_product_key  ON gold.fact_sales (product_key);
CREATE INDEX IF NOT EXISTS ix_fact_sales_customer_key ON gold.fact_sales (customer_key);
CREATE INDEX IF NOT EXISTS ix_fact_sales_country_key  ON gold.fact_sales (country_key);
